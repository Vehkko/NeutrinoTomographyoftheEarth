#!/usr/bin/env bash
set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/common.sh"

section "Building nuSQuIDS 1.13.3"

SOURCE="${SRC}/nusquids"
WORK="${BUILD}/nusquids"

require_dir "${SOURCE}"

# nuSQuIDS' build system assumes src/, include/, resources/, data/
# are relative to the current working directory.
rm -rf "${WORK}"
mkdir -p "${WORK}"

cp -a "${SOURCE}/." "${WORK}/"
rm -rf "${WORK}/.git"

cd "${WORK}"

# CC/CXX come from the environment exported by common.sh.
# Do NOT pass CC=... or CXX=... as configure arguments.
./configure \
    --prefix="${PREFIX}" \
    --libdir=lib \
    --bindir=bin \
    --with-gsl="${PREFIX}" \
    --with-hdf5="${PREFIX}" \
    --with-squids="${PREFIX}"

# Sanity check: make sure the generated Makefile really uses icpx.
grep -q "^CXX=${CXX}$" Makefile ||
    fatal "nuSQuIDS configure did not select the expected compiler: ${CXX}"

# ------------------------------------------------------------------
# nuSQuIDS' legacy configure script overwrites both CXXFLAGS and
# LDFLAGS in the generated Makefile.
#
# Patch the generated Makefile instead of overriding variables on the
# make command line. Command-line LDFLAGS would otherwise erase the
# dependency link flags generated by nuSQuIDS.
# ------------------------------------------------------------------

NUSQUIDS_CXXFLAGS="-std=c++11 ${CXXFLAGS}"

sed -i \
    "s|^CXXFLAGS= -std=c++11$|CXXFLAGS= ${NUSQUIDS_CXXFLAGS}|" \
    Makefile

sed -i \
    "s|^LDFLAGS= |LDFLAGS= ${LDFLAGS} |" \
    Makefile

# ------------------------------------------------------------------
# Important for LTO:
#
# nuSQuIDS normally compiles a marker containing "..._A_..." and
# make install binary-patches libnuSQuIDS.a/.so with sed to change
# it to "..._B_...".
#
# Do not run sed over LLVM LTO archives.
# Compile the installed-data-path state directly instead.
# ------------------------------------------------------------------

RESOURCE_PATH_HEADER="build/resource_paths.h"

[[ -f "${RESOURCE_PATH_HEADER}" ]] ||
    fatal "nuSQuIDS resource path header was not generated"

sed -i \
    's/NUSQUIDS_DATA_PATH_INSTALL_FLAG_PREFIX_A_NUSQUIDS_DATA_PATH_INSTALL_FLAG_SUFFIX/NUSQUIDS_DATA_PATH_INSTALL_FLAG_PREFIX_B_NUSQUIDS_DATA_PATH_INSTALL_FLAG_SUFFIX/g' \
    "${RESOURCE_PATH_HEADER}"

grep -Fq \
    "NUSQUIDS_DATA_PATH_INSTALL_FLAG_PREFIX_B_NUSQUIDS_DATA_PATH_INSTALL_FLAG_SUFFIX" \
    "${RESOURCE_PATH_HEADER}" ||
    fatal "Failed to select installed nuSQuIDS data path"

# Verify LTO and archive tool selection.
grep -Fq -- "-flto=full" Makefile ||
    fatal "nuSQuIDS Makefile does not contain -flto=full"

grep -q "^AR=${AR}$" Makefile ||
    fatal "nuSQuIDS did not select llvm-ar"

# ------------------------------------------------------------------
# Build
# ------------------------------------------------------------------

make -j"${JOBS}"

# ------------------------------------------------------------------
# Manual installation
#
# Do NOT use nuSQuIDS' original `make install`: it pipes the built
# archive/shared library through sed. A byte-for-byte copy is safer
# for LLVM LTO archives.
# ------------------------------------------------------------------

mkdir -p \
    "${PREFIX}/include/nuSQuIDS" \
    "${PREFIX}/lib/pkgconfig" \
    "${PREFIX}/bin" \
    "${PREFIX}/share/nuSQuIDS"

cp include/nuSQuIDS/*.h \
    "${PREFIX}/include/nuSQuIDS/"

cp lib/libnuSQuIDS.a \
    "${PREFIX}/lib/"

# Keep the shared version too for tools which may still want it.
rm -f "${PREFIX}/lib"/libnuSQuIDS.so*
cp -a lib/libnuSQuIDS.so* \
    "${PREFIX}/lib/"

cp lib/nusquids.pc \
    "${PREFIX}/lib/pkgconfig/"

cp lib/nusquids-config \
    "${PREFIX}/bin/"
chmod +x "${PREFIX}/bin/nusquids-config"

rm -rf "${PREFIX}/share/nuSQuIDS"
mkdir -p "${PREFIX}/share/nuSQuIDS"
cp -a data/. \
    "${PREFIX}/share/nuSQuIDS/"

echo
echo "[done] nuSQuIDS"
